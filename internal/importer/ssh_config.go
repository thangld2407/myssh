package importer

import (
	"bufio"
	"io"
	"strconv"
	"strings"
)

// ParsedSSHHost represents a host entry parsed from ~/.ssh/config.
type ParsedSSHHost struct {
	Name         string `json:"name"`
	Hostname     string `json:"hostname"`
	Port         int    `json:"port"`
	Username     string `json:"username"`
	IdentityFile string `json:"identity_file,omitempty"`
	ProxyJump    string `json:"proxy_jump,omitempty"`
}

// ParseSSHConfig parses OpenSSH config format and extracts individual host entries.
func ParseSSHConfig(r io.Reader) ([]ParsedSSHHost, error) {
	scanner := bufio.NewScanner(r)
	var hosts []ParsedSSHHost
	var current *ParsedSSHHost

	defaultUser := "root"
	defaultPort := 22

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		// Split on whitespace or '='
		parts := strings.Fields(line)
		if len(parts) < 2 {
			continue
		}

		key := strings.ToLower(parts[0])
		val := strings.Join(parts[1:], " ")
		val = strings.Trim(val, `"'`)

		if key == "host" {
			// Save previous host if valid
			if current != nil && current.Name != "" && current.Name != "*" {
				if current.Hostname == "" {
					current.Hostname = current.Name
				}
				if current.Port == 0 {
					current.Port = defaultPort
				}
				if current.Username == "" {
					current.Username = defaultUser
				}
				hosts = append(hosts, *current)
			}

			// Do not treat wildcard "*" as an imported host
			if val == "*" {
				current = nil
				continue
			}

			current = &ParsedSSHHost{
				Name: val,
				Port: defaultPort,
			}
			continue
		}

		if current == nil {
			// Global configurations
			if key == "user" && val != "" {
				defaultUser = val
			} else if key == "port" {
				if p, err := strconv.Atoi(val); err == nil && p > 0 {
					defaultPort = p
				}
			}
			continue
		}

		switch key {
		case "hostname":
			current.Hostname = val
		case "user":
			current.Username = val
		case "port":
			if p, err := strconv.Atoi(val); err == nil && p > 0 {
				current.Port = p
			}
		case "identityfile":
			current.IdentityFile = val
		case "proxyjump":
			current.ProxyJump = val
		}
	}

	// Flush trailing host
	if current != nil && current.Name != "" && current.Name != "*" {
		if current.Hostname == "" {
			current.Hostname = current.Name
		}
		if current.Port == 0 {
			current.Port = defaultPort
		}
		if current.Username == "" {
			current.Username = defaultUser
		}
		hosts = append(hosts, *current)
	}

	return hosts, scanner.Err()
}

// ExportableHost represents the fields required to generate an OpenSSH config entry.
type ExportableHost struct {
	Name         string
	Hostname     string
	Port         int
	Username     string
	IdentityFile string
	ProxyJump    string
}

// GenerateSSHConfig generates valid ~/.ssh/config content from a list of ExportableHost entries.
func GenerateSSHConfig(hosts []ExportableHost) string {
	var b strings.Builder
	b.WriteString("# Generated by MySSH Bastion\n\n")

	for _, h := range hosts {
		name := strings.TrimSpace(h.Name)
		if name == "" {
			name = h.Hostname
		}
		if name == "" {
			continue
		}

		b.WriteString("Host " + name + "\n")
		if h.Hostname != "" {
			b.WriteString("    HostName " + h.Hostname + "\n")
		}
		if h.Username != "" {
			b.WriteString("    User " + h.Username + "\n")
		}
		if h.Port > 0 && h.Port != 22 {
			b.WriteString("    Port " + strconv.Itoa(h.Port) + "\n")
		}
		if h.ProxyJump != "" {
			b.WriteString("    ProxyJump " + h.ProxyJump + "\n")
		}
		if h.IdentityFile != "" {
			b.WriteString("    IdentityFile " + h.IdentityFile + "\n")
		}
		b.WriteString("\n")
	}

	return b.String()
}

